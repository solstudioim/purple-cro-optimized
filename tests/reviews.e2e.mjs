/** Reversible local admin/configurator and reusable review placement journeys. */
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdirSync } from 'node:fs';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
assert.ok(process.env.POT_WP_PATH && process.env.POT_ARTIFACTS);
const wpArgs = ['-d', 'error_reporting=22527', '/usr/local/bin/wp'];
const wp = (code) => execFileSync(process.env.POT_PHP || 'php', [...wpArgs, 'eval', code, `--path=${process.env.POT_WP_PATH}`], { encoding: 'utf8' }).trim();
const run = (mode) => execFileSync(process.env.POT_PHP || 'php', [...wpArgs, 'eval-file', 'tests/reviews-integration.php', mode, `--path=${process.env.POT_WP_PATH}`], { encoding: 'utf8' }).trim();
const site = wp('echo home_url();');
assert.match(new URL(site).hostname, /^(localhost|127\.0\.0\.1)$/);
mkdirSync(process.env.POT_ARTIFACTS, { recursive: true });
const original = wp('echo base64_encode(serialize(array(get_option("pot_settings"),get_option("pot_checkout_settings"),get_option("pot_checkout_content_id",false))));');
const fixture = JSON.parse(run('prepare').split('\n').at(-1));
const browser = await chromium.launch({ headless: true });
let pageId = 0;
let productId = 0;
try {
 const admin = await browser.newContext();
 const page = await admin.newPage();
 page.setDefaultTimeout(20000);
 await page.goto(`${site}/wp-login.php`);
 await page.locator('#user_login').fill(process.env.POT_TEST_USER || 'compat');
 await page.locator('#user_pass').fill(process.env.POT_TEST_PASSWORD || 'local-development-only');
 await Promise.all([page.waitForURL((url) => !url.pathname.endsWith('wp-login.php')), page.locator('#wp-submit').click()]);
 await page.goto(`${site}/wp-admin/admin.php?page=purple-optimize&section=privacy`);
 await page.getByRole('heading', { name: 'Social proof', exact: true }).waitFor();
 await page.getByRole('heading', { name: 'Recent purchases', exact: true }).waitFor();
 await page.getByRole('heading', { name: 'Reviews & testimonials', exact: true }).waitFor();
 const before = wp('echo wp_json_encode(pot_settings());');
 const builder = page.locator('#pot-reviews-configurator');
 await builder.locator('[name=source]').selectOption('products');
 await builder.locator('#pot-reviews-product-search + .select2 .select2-search__field').fill('Review fixture public');
 await page.getByRole('option', { name: /Review fixture public/ }).first().click();
 assert.equal(await builder.locator('[name=products]').inputValue(), String(fixture.public), 'Native Woo product search fills product IDs');
 await builder.locator('[name=layout]').selectOption('rotator');
 await builder.locator('[name=heading]').fill('Customer stories');
 await builder.getByRole('button', { name: 'Generate shortcode & preview' }).click();
 await page.locator('#pot-reviews-result').waitFor({ state: 'visible' });
 const shortcode = await page.locator('#pot-reviews-shortcode').inputValue();
 assert.match(shortcode, /source="products"/);
 assert.match(shortcode, new RegExp(`products="${fixture.public}"`));
 assert.equal(await page.locator('#pot-reviews-preview .pot-testimonial').count(), 2);
 await page.locator('#pot-reviews-preview .pot-testimonials-controls').waitFor({ state: 'visible' });
 const previewNonce = await page.evaluate(() => window.potReviewBuilder.nonce);
 const invalid = await admin.request.post(`${site}/wp-admin/admin-ajax.php`, { form: { action: 'pot_preview_reviews', nonce: 'invalid' } });
 assert.equal(invalid.status(), 403);
 const missing = await admin.request.post(`${site}/wp-admin/admin-ajax.php`, { form: { action: 'pot_preview_reviews', nonce: previewNonce, 'config[source]': 'products', 'config[products]': '' } });
 assert.equal(missing.status(), 400);
 await builder.locator('[name=source]').selectOption('reviews');
 assert.equal(await page.locator('#pot-reviews-result').isVisible(), false, 'Changed selections invalidate old copy/preview');
 await builder.locator('[name=review_ids]').fill(String(fixture.comments[2]));
 await builder.locator('[name=layout]').selectOption('list');
 await builder.getByRole('button', { name: 'Generate shortcode & preview' }).click();
 await page.locator('#pot-reviews-result').waitFor({ state: 'visible' });
 assert.match(await page.locator('#pot-reviews-preview').innerText(), /Another product review/);
 assert.equal(before, wp('echo wp_json_encode(pot_settings());'), 'Generating shortcodes must never change existing settings');
 await page.screenshot({ path: `${process.env.POT_ARTIFACTS}/social-proof-configurator.png`, fullPage: true });
 await admin.close();
 pageId = Number(wp(`echo wp_insert_post(array('post_type'=>'page','post_status'=>'publish','post_title'=>'Local review placements','post_content'=>'<!-- wp:shortcode -->${shortcode}<!-- /wp:shortcode --><!-- wp:shortcode -->[purple_optimize_reviews source="reviews" review_ids="${fixture.comments[2]}" author="anonymous"]<!-- /wp:shortcode -->'));`));
 const pageUrl = wp(`echo get_permalink(${pageId});`);
 const guest = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
 const front = await guest.newPage();
 const errors = [];
 front.on('pageerror', (error) => errors.push(error.message));
 const unauth = await guest.request.post(`${site}/wp-admin/admin-ajax.php`, { form: { action: 'pot_preview_reviews', nonce: previewNonce } });
 assert.ok([400, 403].includes(unauth.status()));
 await front.goto(pageUrl, { waitUntil: 'networkidle' });
 assert.equal(await front.locator('.pot-testimonials').count(), 2, 'Independent shortcodes render independent selections');
 const rotator = front.locator('[data-pot-review-rotator]').first();
 assert.equal(await rotator.locator('.pot-testimonial:visible').count(), 1);
 const first = await rotator.locator('.pot-testimonial:visible').innerText();
 await rotator.getByRole('button', { name: 'Next review' }).click();
 assert.notEqual(await rotator.locator('.pot-testimonial:visible').innerText(), first);
 await rotator.getByRole('button', { name: 'Previous review' }).click();
 assert.equal(await rotator.locator('.pot-testimonial:visible').innerText(), first);
 assert.match(await front.locator('.pot-testimonials').last().innerText(), /Customer/);
 const typography = await rotator.evaluate((el) => ({ component: getComputedStyle(el).fontFamily, parent: getComputedStyle(el.parentElement).fontFamily }));
 assert.equal(typography.component, typography.parent, 'Review typography inherits the theme');
 await front.screenshot({ path: `${process.env.POT_ARTIFACTS}/reviews-desktop.png`, fullPage: true });
 await front.setViewportSize({ width: 390, height: 844 });
 assert.ok(await front.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
 await front.screenshot({ path: `${process.env.POT_ARTIFACTS}/reviews-mobile.png`, fullPage: true });
 // Checkout dynamically hydrates restricted content from the Store API.
 productId = Number(wp('$p=new WC_Product_Simple();$p->set_name("Local review cart fixture");$p->set_status("publish");$p->set_regular_price(12);echo $p->save();'));
 wp(`$s=pot_settings();$s['offer_funnel']=0;update_option('pot_settings',$s);$c=pot_checkout_settings();$c['content_enabled']=1;update_option('pot_checkout_settings',$c);update_option('pot_checkout_content_id',${fixture.document});`);
 await front.goto(`${site}/?add-to-cart=${productId}`, { waitUntil: 'networkidle' });
 await front.goto(`${site}/checkout/`, { waitUntil: 'networkidle' });
 const checkout = front.locator('.pot-checkout-content [data-pot-review-rotator]');
 await checkout.waitFor({ state: 'visible' });
 await checkout.getByRole('button', { name: 'Next review' }).waitFor({ state: 'visible' });
 assert.equal(await checkout.locator('.pot-testimonial:visible').count(), 1);
 await front.screenshot({ path: `${process.env.POT_ARTIFACTS}/reviews-checkout-mobile.png`, fullPage: true });
 assert.deepEqual(errors, []);
 await guest.close();
 const noJs = await browser.newContext({ javaScriptEnabled: false });
 const plain = await noJs.newPage();
 await plain.goto(pageUrl);
 assert.equal(await plain.locator('.pot-testimonial:visible').count(), 3, 'Without JS all selected reviews remain readable');
 await noJs.close();
 // Reduced motion disables autoplay while retaining manual navigation.
 wp(`wp_update_post(array('ID'=>${pageId},'post_content'=>'<!-- wp:shortcode -->[purple_optimize_reviews source="products" products="${fixture.public}" layout="rotator" autoplay="5"]<!-- /wp:shortcode -->'));`);
 const reduced = await browser.newContext({ reducedMotion: 'reduce' });
 const reducedPage = await reduced.newPage();
 await reducedPage.goto(pageUrl, { waitUntil: 'networkidle' });
 assert.equal(await reducedPage.locator('[data-review-play]').getAttribute('aria-pressed'), 'false');
 await reduced.close();
 const motion = await browser.newContext();
 const motionPage = await motion.newPage();
 await motionPage.goto(pageUrl, { waitUntil: 'networkidle' });
 const motionRoot = motionPage.locator('[data-pot-review-rotator]');
 const motionFirst = await motionRoot.locator('.pot-testimonial:visible').innerText();
 await motionPage.waitForFunction((first) => document.querySelector('[data-pot-review-rotator] .pot-testimonial:not([hidden])')?.innerText !== first, motionFirst, { timeout: 12000 });
 await motionRoot.hover();
 const hovered = await motionRoot.locator('.pot-testimonial:visible').innerText();
 await motionPage.waitForTimeout(5500);
 assert.equal(await motionRoot.locator('.pot-testimonial:visible').innerText(), hovered, 'Hover pauses automatic rotation');
 await motionRoot.locator('[data-review-play]').click();
 assert.equal(await motionRoot.locator('[data-review-play]').getAttribute('aria-pressed'), 'false');
 await motionPage.mouse.move(0, 0);
 await motionPage.locator('body').click({ position: { x: 1, y: 1 } });
 await motionPage.waitForTimeout(5500);
 assert.equal(await motionRoot.locator('.pot-testimonial:visible').innerText(), hovered, 'Explicit pause persists after hover/focus leave');
 await motion.close();
 console.log('PASS: Social proof builder, generated selections, authenticated preview/nonce checks, no settings mutations, static/multi-instance rotator, desktop/mobile theme inheritance, hydrated checkout, no-JS fallback and reduced motion.');
} finally {
 wp(`$v=unserialize(base64_decode('${original}'));update_option('pot_settings',$v[0]);update_option('pot_checkout_settings',$v[1]);if(false===$v[2]){delete_option('pot_checkout_content_id');}else{update_option('pot_checkout_content_id',$v[2]);}if(${pageId})wp_delete_post(${pageId},true);if(${productId})wp_delete_post(${productId},true);`);
 run('cleanup');
 await browser.close();
}
